import { assert, load } from './runtime.mjs';
import { installDocument } from './dom.mjs';
const press = installDocument();
const m = await load('web/index.ts');
assert.equal(m.buttonClass(), 'btn');
assert.equal(m.buttonClass('ghost', { block: true }), 'btn ghost block');
const options = { icon: 'mic', iconOff: 'micOff', label: 'On', labelOff: 'Off' };
assert.deepEqual(m.toggleView(true, options), { class: 'toggle on', icon: 'mic', label: 'On' });
assert.deepEqual(m.toggleView(false, options), { class: 'toggle off', icon: 'micOff', label: 'Off' });
assert.equal(m.formatCount(1234), '1,234');
assert.equal(m.mmss(59001), '1:00');
assert.equal(m.mmss(-1), '0:00');
assert.deepEqual(m.normaliseHelpSections([{ title: ' Help ', body: ' text ' }, { title: '', body: '' }]), [{ title: 'Help', body: 'text' }]);
let clicked = 0;
const button = m.iconButton({ icon: 'play', label: 'Start game', onClick: () => clicked++ });
assert.equal(button.getAttribute('aria-label'), 'Start game');
button.click();
assert.equal(clicked, 1);
const disabled = m.iconButton({ icon: 'play', label: 'Start game', disabled: true, glow: true, onClick: () => clicked++ });
assert.equal(disabled.disabled, true);
assert.ok(!disabled.className.split(' ').includes('glow'));
disabled.click();
assert.equal(clicked, 1);
const changes = [];
const toggle = m.toggle({ on: false, icon: 'mic', label: 'Microphone', onChange: value => changes.push(value) });
assert.equal(toggle.getAttribute('aria-pressed'), 'false');
toggle.click();
assert.deepEqual(changes, [true]);
let closed = 0;
const dialog = m.dialog({ title: 'Question', body: ['Confirm?'], onClose: () => closed++ });
assert.equal(dialog.el.getAttribute('role'), 'dialog');
assert.equal(dialog.el.getAttribute('aria-modal'), 'true');
press('Enter');
assert.equal(closed, 0);
press('Escape');
assert.equal(closed, 1);
assert.equal(dialog.el.removed, true);
dialog.close();
press('Escape');
assert.equal(closed, 1);
